CREATE OR REPLACE FUNCTION get_qtd_prox_vencimentos(COD_CD NUMBER)
RETURN NUMBER
IS
DATA_VALIDADE_MAX DATE := SYSDATE + 5;
DATA_PRODUTO produtos%ROWTYPE;
CONTADOR NUMBER := 0;
CURSOR produtos IS
    SELECT p.*, pecd.quantidade
    FROM produto p
    JOIN PROD_ESTOCADO_CENT_DIST pecd
        ON pecd.CODIGO_PRODUTO = p.codigo
        AND pecd.CODIGO_CENTRO_DISTRIBUICAO = COD_CD
    WHERE p.DATA_VALIDADE > SYSDATE
        AND p.DATA_VALIDADE < DATA_VALIDADE_MAX;

BEGIN
    OPEN produtos;
    LOOP
        FETCH produtos INTO DATA_PRODUTO;
        EXIT WHEN produtos%NOTFOUND;
        CONTADOR := CONTADOR + DATA_PRODUTO.quantidade;
    END LOOP;
    CLOSE produtos;

    RETURN CONTADOR;
END;